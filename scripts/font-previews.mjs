// Generates src/font-previews.js: each bundled font's name drawn with its own
// glyphs as an SVG path, so the font picker can preview fonts that are not
// loaded yet (no extra font download). Run: node scripts/font-previews.mjs
import fs from "node:fs";
import opentype from "opentype.js";
import { FONT_CATALOG } from "../src/fonts.js";
const SIZE = 14;
const out = {};
for (const f of FONT_CATALOG) {
  const buf = fs.readFileSync(`public/fonts/${f.file}`);
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const text = `${f.label}  あア漢`;
  const missing = [...text].filter((c) => c !== " " && !(font.charToGlyphIndex(c) > 0));
  if (missing.length) throw Error(`${f.id}: missing ${missing.join("")}`);
  const path = font.getPath(text, 0, SIZE, SIZE);
  const box = path.getBoundingBox();
  const pad = 1;
  out[f.id] = {
    d: path.toPathData(1),
    viewBox: [box.x1 - pad, box.y1 - pad, box.x2 - box.x1 + pad * 2, box.y2 - box.y1 + pad * 2].map((n) => Number(n.toFixed(2))).join(" "),
    width: Number((box.x2 - box.x1 + pad * 2).toFixed(2)),
    height: Number((box.y2 - box.y1 + pad * 2).toFixed(2)),
  };
}
fs.writeFileSync("src/font-previews.js", `// Generated by scripts/font-previews.mjs from public/fonts. Do not edit.\nexport const FONT_PREVIEWS = ${JSON.stringify(out)};\n`);
console.log(Object.entries(out).map(([k, v]) => `${k}: ${v.d.length} chars`).join("\n"));
